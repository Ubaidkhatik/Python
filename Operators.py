# Operators
print('Arithmetic Operator:')
a = 37
b = 98

# Addition
print(a + b)
# Subtraction
print(a - b)
# Multiplication
print(a * b)
# Division
print(a / b)
# Modulo
print(a % b)

print('\nComparison Operator:')
c = 65
d = 39

# Equal to
print(c == d)
# Not equal to
print(c != d)
# Less than or equal to
print(c <= d)
# Greater than or equal to
print(c >= d)
# Greater than
print(c > d)
# Less than
print(c < d)

print('\nLogical Operator:')
e = 41
f = 97

# and
print(e < f and f > e)
# or
print(e == 37 or f > e)
# not
print(not (e > f))


print('\nAssignment Operator:')
g = 85
#+assign
g+=7
print(g)
#-assign
g-=3
print(g)
#*assign
g*=2
print(g) 
#/assign
g/=2
print(g)
#%assign 
g%=3
print(g)

